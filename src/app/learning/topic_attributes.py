def _observation_hash(
    *,
    channel_id: str,
    attribute_name: str,
    attribute_bucket: str,
    metric_name: str,
    source_publication_ids: list[int],
) -> str:
    payload = json.dumps(
        {
            "channel_id": channel_id,
            "attribute_name": attribute_name,
            "attribute_bucket": attribute_bucket,
            "metric_name": metric_name,
            "source_publication_ids": sorted(source_publication_ids),
            "schema_version": TOPIC_ATTR_SCHEMA_VERSION,
            "observer_version": TOPIC_ATTR_OBSERVER_VERSION,
        },
        sort_keys=True,
    )
    return hashlib.sha256(payload.encode()).hexdigest()


def _upsert_topic_attribute_observation(
    conn: sqlite3.Connection,
    *,
    channel_id: str,
    workspace_id: str | None,
    attribute_name: str,
    bucket: str,
    metric_name: str,
    values: list[float],
    pub_ids: list[int],
    topic_ids: list[int],
    domain_families: set[str],
    baseline_mean: float | None,
    baseline_median: float | None,
) -> TopicAttributePerformanceObservation:
    now = _now()
    stats = compute_stats(values)
    n = int(stats.get("publication_count", 0))
    mean = stats.get("mean")
    abs_diff = (mean - baseline_mean) if (mean is not None and baseline_mean is not None) else None
    rel_diff = (
        (abs_diff / baseline_mean)
        if (abs_diff is not None and baseline_mean not in (None, 0))
        else None
    )

    distinct_topics = sorted(set(topic_ids))

    # Closure-audit fix (Part 19/20): maturity for TOPIC-SEMANTIC evidence
    # must be classified by DISTINCT TOPIC count, not raw publication
    # count. The goal is reusable topic characteristics — republishing the
    # SAME topic 10 times is one semantic sample repeated 10 times, not 10
    # independent samples, and must never alone manufacture 'actionable'
    # confidence. publication_count is still persisted and shown
    # separately as an exposure/repetition descriptor.
    topic_n = len(distinct_topics)
    maturity = classify_maturity(topic_n)
    # Cross-domain safeguard (Part 22): evidence confined to < 2 distinct
    # domain families is never reported stronger than 'exploratory', even
    # when distinct-topic count alone would justify 'directional'/'actionable'.
    if len(domain_families) < MIN_DISTINCT_DOMAIN_FAMILIES_FOR_STRONG_MATURITY:
        if maturity in ("directional", "actionable"):
            maturity = "exploratory" if topic_n >= 2 else "insufficient"
    pub_ids_sorted = sorted(set(pub_ids))
    input_hash = _observation_hash(
        channel_id=channel_id,
        attribute_name=attribute_name,
        attribute_bucket=bucket,
        metric_name=metric_name,
        source_publication_ids=pub_ids_sorted,
    )
    conn.execute(
        """
        INSERT INTO topic_attribute_performance_observations (
            channel_id, workspace_id, attribute_name, attribute_bucket, metric_name,
            period_type, publication_count, distinct_topic_count, distinct_domain_family_count,
            mean, median, min_value, max_value, std_dev,
            baseline_mean, baseline_median, abs_diff_from_baseline, rel_diff_from_baseline,
            sample_maturity, observation_type,
            source_publication_ids_json, source_topic_ids_json,
            comparison_schema_version, observer_version, input_hash,
            created_at, updated_at
        ) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)
        ON CONFLICT(channel_id, attribute_name, attribute_bucket, metric_name)
        DO UPDATE SET
            workspace_id                    = excluded.workspace_id,
            publication_count               = excluded.publication_count,
            distinct_topic_count            = excluded.distinct_topic_count,
            distinct_domain_family_count    = excluded.distinct_domain_family_count,
            mean                            = excluded.mean,
            median                          = excluded.median,
            min_value                       = excluded.min_value,
            max_value                       = excluded.max_value,
            std_dev                         = excluded.std_dev,
            baseline_mean                   = excluded.baseline_mean,
            baseline_median                 = excluded.baseline_median,
            abs_diff_from_baseline          = excluded.abs_diff_from_baseline,
            rel_diff_from_baseline          = excluded.rel_diff_from_baseline,
            sample_maturity                 = excluded.sample_maturity,
            source_publication_ids_json     = excluded.source_publication_ids_json,
            source_topic_ids_json           = excluded.source_topic_ids_json,
            comparison_schema_version       = excluded.comparison_schema_version,
            observer_version                = excluded.observer_version,
            input_hash                      = excluded.input_hash,
            updated_at                      = excluded.updated_at
        """,
        (
            channel_id,
            workspace_id,
            attribute_name,
            bucket,
            metric_name,
            "lifetime",
            n,
            len(distinct_topics),
            len(domain_families),
            mean,
            stats.get("median"),
            stats.get("min_value"),
            stats.get("max_value"),
            stats.get("std_dev"),
            baseline_mean,
            baseline_median,
            abs_diff,
            rel_diff,
            maturity,
            "association",
            json.dumps(pub_ids_sorted),
            json.dumps(distinct_topics),
            TOPIC_ATTR_SCHEMA_VERSION,
            TOPIC_ATTR_OBSERVER_VERSION,
            input_hash,
            now,
            now,
        ),
    )
    row = conn.execute(
        """
        SELECT * FROM topic_attribute_performance_observations
         WHERE channel_id = ? AND attribute_name = ? AND attribute_bucket = ? AND metric_name = ?
        """,
        (channel_id, attribute_name, bucket, metric_name),
    ).fetchone()
    return TopicAttributePerformanceObservation.from_row(row)  # type: ignore[arg-type]


def run_topic_attribute_learning(
    conn: sqlite3.Connection,
    *,
    channel_id: str,
    workspace_id: str | None = None,
) -> TopicAttributeLearningResult:
    """Compute and persist topic-attribute performance observations.

    Mirrors run_cross_publication_learning's shape and invariants exactly
    (Part 27): read-only on analytics/topic-attribute tables, writes only to
    topic_attribute_performance_observations, ZERO provider calls, safe to
    call repeatedly (idempotent upsert). Intended to be invoked from the
    same point in the existing learning pipeline as
    run_cross_publication_learning — never a new scheduler.

    A publication contributes to an attribute/bucket group only if:
      - its topic has a persisted attribute evaluation (get_topic_attributes),
      - it has a lifetime, non-seed OUTCOME_METRICS row (via the same
        _get_lifetime_metrics used by cross-publication learning), and
      - its lifetime `views` metric is >= MIN_VIEWS_FOR_LEARNING (Part 18 —
        reused, not reinvented; excludes zero/near-zero-exposure noise).
    """
    if not _table_exists(conn, "topic_attribute_performance_observations"):
        return TopicAttributeLearningResult(channel_id=channel_id, computed_at=_now())

    # Closure-audit fix: discover (publication, topic) pairs via the
    # canonical publications -> publishing_plans lineage, NOT
    # content_feature_snapshots. Topic-attribute learning is semantic and
    # must not depend on a creative-feature extraction row existing —
    # confirmed live that a valid, opportunity-linked, published topic can
    # have a publication with zero content_feature_snapshot rows (an early
    # direct-publish that predates the feature-extraction pipeline).
    # content_feature_snapshots remains correctly scoped to creative-factor
    # learning only (feature_performance_observations).
    pub_rows = conn.execute(
        """
        SELECT DISTINCT pub.id AS publication_id, pp.topic_id
          FROM publications pub
          JOIN publishing_plans pp ON pub.publishing_plan_id = pp.id
         WHERE pub.channel_id = ?
        """,
        (channel_id,),
    ).fetchall()
    pub_topic: dict[int, int] = {r["publication_id"]: r["topic_id"] for r in pub_rows}
    pub_ids = list(pub_topic.keys())

    lifetime_metrics = _get_lifetime_metrics(conn, pub_ids)

    # Exposure gate (Part 18): a publication's views metric must clear
    # MIN_VIEWS_FOR_LEARNING before ANY of its metrics contribute evidence.
    eligible_pub_ids: list[int] = []
    for pub_id in pub_ids:
        views_entry = lifetime_metrics.get(pub_id, {}).get("views")
        if views_entry is not None and views_entry[0] >= MIN_VIEWS_FOR_LEARNING:
            eligible_pub_ids.append(pub_id)

    # Channel baselines: reuse channel_performance_baselines (Part 20) rather
    # than computing a second, competing baseline.
    baseline_rows = conn.execute(
        "SELECT metric_name, mean, median FROM channel_performance_baselines WHERE channel_id = ?",
        (channel_id,),
    ).fetchall()
    baselines = {r["metric_name"]: (r["mean"], r["median"]) for r in baseline_rows}

    topics_with_attributes = 0
    # {(attribute_name, bucket, metric_name): {"values", "pubs", "topics", "domains"}}
    groups: dict[tuple[str, str, str], dict[str, object]] = {}

    for pub_id in eligible_pub_ids:
        topic_id = pub_topic[pub_id]
        attrs = get_topic_attributes(conn, topic_id)
        if attrs is None or not attrs.evaluated:
            continue
        topics_with_attributes += 1
        domain_family = get_domain_family_for_publication(conn, pub_id)
        pub_metrics = lifetime_metrics.get(pub_id, {})
        for attribute_name in TOPIC_ATTRIBUTE_NAMES:
            value = getattr(attrs, attribute_name)
            bucket = attribute_bucket(value)
            if bucket is None:
                continue
            for metric_name, (metric_value, _snap_ids) in pub_metrics.items():
                if metric_name not in OUTCOME_METRICS:
                    continue
                key = (attribute_name, bucket, metric_name)
                g = groups.setdefault(
                    key, {"values": [], "pubs": [], "topics": [], "domains": set()}
                )
                g["values"].append(metric_value)  # type: ignore[union-attr]
                g["pubs"].append(pub_id)  # type: ignore[union-attr]
                g["topics"].append(topic_id)  # type: ignore[union-attr]
                if domain_family is not None:
                    g["domains"].add(domain_family)  # type: ignore[union-attr]

    metrics_with_data: set[str] = set()
    observations_computed = 0
    current_keys: set[tuple[str, str, str]] = set()
    for (attribute_name, bucket, metric_name), g in groups.items():
        baseline_mean, baseline_median = baselines.get(metric_name, (None, None))
        _upsert_topic_attribute_observation(
            conn,
            channel_id=channel_id,
            workspace_id=workspace_id,
            attribute_name=attribute_name,
            bucket=bucket,
            metric_name=metric_name,
            values=g["values"],  # type: ignore[arg-type]
            pub_ids=g["pubs"],  # type: ignore[arg-type]
            topic_ids=g["topics"],  # type: ignore[arg-type]
            domain_families=g["domains"],  # type: ignore[arg-type]
            baseline_mean=baseline_mean,
            baseline_median=baseline_median,
        )
        observations_computed += 1
        metrics_with_data.add(metric_name)
        current_keys.add((attribute_name, bucket, metric_name))

    # Closure-audit fix: prune stale rows. A bucket that had supporting
    # evidence in a PAST run but has none in THIS run (e.g. its only
    # publication's analytics dropped below MIN_VIEWS_FOR_LEARNING, or the
    # topic's re-characterized attribute value moved to a different
    # bucket) must not remain visible forever — only rows this run
    # actually recomputed survive for this channel.
    existing_rows = conn.execute(
        "SELECT attribute_name, attribute_bucket, metric_name"
        " FROM topic_attribute_performance_observations WHERE channel_id = ?",
        (channel_id,),
    ).fetchall()
    for row in existing_rows:
        key = (row["attribute_name"], row["attribute_bucket"], row["metric_name"])
        if key not in current_keys:
            conn.execute(
                "DELETE FROM topic_attribute_performance_observations"
                " WHERE channel_id = ? AND attribute_name = ?"
                " AND attribute_bucket = ? AND metric_name = ?",
                (channel_id, *key),
            )

    conn.commit()
    return TopicAttributeLearningResult(
        channel_id=channel_id,
        publication_count=len(eligible_pub_ids),
        topics_with_attributes=topics_with_attributes,
        observations_computed=observations_computed,
        metrics_with_data=sorted(metrics_with_data),
        computed_at=_now(),
    )


def get_attribute_observations(
    conn: sqlite3.Connection,
    *,
    channel_id: str,
    attribute_name: str | None = None,
) -> list[TopicAttributePerformanceObservation]:
    """Raw read model (Part 25): every persisted observation, including
    insufficient-maturity and single-domain rows. Analogous to
    get_feature_observations() for creative factors."""
    if not _table_exists(conn, "topic_attribute_performance_observations"):
        return []
    clauses = ["channel_id = ?"]
    params: list[object] = [channel_id]
    if attribute_name is not None:
        clauses.append("attribute_name = ?")
        params.append(attribute_name)
    where = "WHERE " + " AND ".join(clauses)
    rows = conn.execute(
        f"""
        SELECT * FROM topic_attribute_performance_observations
        {where}
        ORDER BY attribute_name, attribute_bucket, metric_name
        """,
        params,
    ).fetchall()
    return [TopicAttributePerformanceObservation.from_row(r) for r in rows]


def get_decision_useful_attribute_coverage(
    conn: sqlite3.Connection,
    *,
    channel_id: str,
) -> list[TopicAttributePerformanceObservation]:
    """Decision-useful read model (Part 26): drops rows that cannot yet
    support a claim.

    A row is included only when:
      - sample_maturity != 'insufficient', AND
      - publication_count >= 2, AND
      - distinct_domain_family_count >= 2 for anything above 'exploratory'
        (already enforced when the row was computed — see
        _upsert_topic_attribute_observation's maturity cap — but a
        single-domain 'exploratory' row IS still shown here, matching the
        brief's explicit "recommended: decision-useful UI may show
        EXPLORATORY only when publication_count >= 2 AND
        distinct_domain_family_count >= 2; otherwise raw-only" rule).
    """
    raw = get_attribute_observations(conn, channel_id=channel_id)
    useful: list[TopicAttributePerformanceObservation] = []
    for ob in raw:
        if ob.sample_maturity == "insufficient":
            continue
        if ob.publication_count < 2:
            continue
        if ob.sample_maturity == "exploratory" and ob.distinct_domain_family_count < 2:
            continue
        useful.append(ob)
    return useful
