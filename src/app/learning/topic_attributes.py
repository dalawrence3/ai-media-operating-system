ATTRIBUTE_BUCKET_LOW = "low"
ATTRIBUTE_BUCKET_MEDIUM = "medium"
ATTRIBUTE_BUCKET_HIGH = "high"


def attribute_bucket(value: float | None) -> str | None:
    """Fixed-band bucket for a 0..1 attribute value. None is never bucketed."""
    if value is None:
        return None
    if value < 0.4:
        return ATTRIBUTE_BUCKET_LOW
    if value < 0.7:
        return ATTRIBUTE_BUCKET_MEDIUM
    return ATTRIBUTE_BUCKET_HIGH


def _normalize_domain_family(domain_family: str | None) -> str | None:
    """Minimal deterministic normalization for concentration counting only —
    mirrors cold_start.py's own Phase 18H.B.1 precedent exactly: strip,
    casefold, collapse whitespace. "Science", " science ", "SCIENCE" all
    count as the same family; the original human-readable value is what
    gets persisted, this is used only to compare/count. Empty/whitespace-
    only normalizes to None (unknown), never to an empty-string family."""
    if domain_family is None:
        return None
    normalized = " ".join(domain_family.strip().casefold().split())
    return normalized or None


