"""Phase 18H.C — Topic-attribute observation stack.

Answers: "Which semantic CHARACTERISTICS of a topic's subject matter tend to
be associated with strong performance on this channel, independent of which
specific domain (science, finance, history, ...) the topic happens to be in?"

Seven descriptive, 0..1, channel-agnostic attributes: practical_utility,
immediate_payoff, curiosity, personal_relevance, surprise,
broad_accessibility, niche_technicality. None is intrinsically good or bad —
relationships with performance are discovered observationally, never assumed.

Canonical entity: TOPIC (src/app/core/models.py Topic / topics table), not
opportunity, not publication, not experiment. Attributes describe subject
matter and must survive different scripts/hooks/renders/re-publications of
the same topic — creative/production factors (speaking rate, scene count,
publish hour, ...) remain a separate layer, tracked by
feature_performance_observations against content_feature_snapshots.

Two ways a topic acquires attributes:

  1. Normal forward path (opportunity-linked topics): the seven attributes
     ride for free on the existing eligibility-semantic-fit LLM call
     (assess_semantic_fit in eligibility_service.py) — zero incremental
     provider calls. Because semantic-fit evaluation and topic promotion are
     two separate, decoupled lifecycle steps (assess_experiment_eligibility
     runs long before promote_opportunity is ever called, often in a
     different process), the attribute values must be persisted on
     opportunity_semantic_fit_results in the interim, then SNAPSHOTTED onto
     the resulting topic_attribute_evaluations row at promotion time via
     snapshot_semantic_fit_attributes_to_topic() — called from
     app.intelligence.repository.promote_opportunity(). This is Part 8's
     "if promotion occurs later" branch, confirmed necessary (not
     speculative) by tracing both functions.

  2. Orphan path (manually-seeded topics with promoted_opportunity_id IS
     NULL — e.g. the historical "renewable energy" topic): no opportunity
     exists to piggyback on, so characterize_topic_directly() makes one
     small, dedicated LLM call per orphan topic, using only topics.title /
     topics.angle (+ operator-supplied channel niche/audience context) and
     never fabricating an opportunity.

Both paths converge on the single canonical persistence surface,
topic_attribute_evaluations, keyed by topic_id — read exclusively through
get_topic_attributes().

Domain family (closure-audit addition): Phase 18H.B.1's domain_family lives
on market_exploration_probes, and NO persisted path links an opportunity or
publication back to the probe that originated it (opportunities.
discovery_run_id references the separate, older discovery_runs pipeline).
Reusing that field here was proven impossible, not merely inconvenient — see
the 18H.C closure audit. Instead, a topic-level SEMANTIC domain_family is
generated by the SAME characterization call as the seven attributes (both
paths), persisted on topic_attribute_evaluations, and read by
get_domain_family_for_publication() via the canonical publication -> topic
lineage. This is a deliberately DIFFERENT domain-family source from
18H.B.1's — never conflated, never backfilled onto historical rows that
predate this column (which simply read as NULL / unknown, exactly like any
other topic that has not yet been characterized).

Design invariants (mirrors cross_publication.py's own, Phase 12C):
  - OBSERVATIONAL ONLY. observation_type='association' always.
  - Attributes are missing, never inferred from titles/domains.
  - No shrinkage, no regression, no interaction terms — plain descriptive
    statistics + maturity gating (app.learning.maturity), exactly like
    feature_performance_observations.
  - Zero provider calls in aggregation — reads persisted data only.
"""

