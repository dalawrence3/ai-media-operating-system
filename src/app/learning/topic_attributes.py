# ── Shared value container (Part 6 — shared between the two extraction paths) ─


@dataclass
class TopicAttributeValues:
    """The seven descriptive attributes + rationale for one topic.

    Shared between the semantic-fit piggyback path and the direct
    orphan-characterization path so both produce/consume the identical
    concept, even though their LLM-facing request schemas are separate
    (eligibility_service._SemanticFitOutput vs.
    _TopicAttributeCharacterizationOutput below) — this is deliberate:
    coupling the shared VALUE shape must never couple the two calls'
    eligibility semantics.
    """

    evaluated: bool = False
    practical_utility: float | None = None
    immediate_payoff: float | None = None
    curiosity: float | None = None
    personal_relevance: float | None = None
    surprise: float | None = None
    broad_accessibility: float | None = None
    niche_technicality: float | None = None
    attribute_rationale: str | None = None
    domain_family: str | None = None

    def as_dict(self) -> dict[str, float | None]:
        return {name: getattr(self, name) for name in TOPIC_ATTRIBUTE_NAMES}

    @classmethod
    def from_row(cls, row: sqlite3.Row | None) -> TopicAttributeValues:
        if row is None:
            return cls(evaluated=False)
        data = dict(row)
        return cls(
            evaluated=True,
            practical_utility=data.get("practical_utility"),
            immediate_payoff=data.get("immediate_payoff"),
            curiosity=data.get("curiosity"),
            personal_relevance=data.get("personal_relevance"),
            surprise=data.get("surprise"),
            broad_accessibility=data.get("broad_accessibility"),
            niche_technicality=data.get("niche_technicality"),
            attribute_rationale=data.get("attribute_rationale"),
            domain_family=data.get("domain_family"),
        )


class _TopicAttributeCharacterizationOutput(BaseModel):
    """Structured response schema for the orphan-path direct-characterization
    call. Deliberately separate from eligibility_service._SemanticFitOutput —
    an orphan topic is never pretended to be an eligibility opportunity."""

    practical_utility: float
    immediate_payoff: float
    curiosity: float
    personal_relevance: float
    surprise: float
    broad_accessibility: float
    niche_technicality: float
    attribute_rationale: str = ""
    domain_family: str = ""

    model_config = {"extra": "forbid"}

    # Deliberately NO lenient-malformed-value tolerance here, unlike
    # eligibility_service._SemanticFitOutput: that schema protects a
    # separately valuable eligibility score/fit_label from being sunk by a
    # bad descriptive field. This schema's entire purpose IS the
    # attributes — if one is malformed, the honest outcome is the whole
    # characterization attempt failing (caught by characterize_topic_
    # directly's existing except-Exception, which returns None and
    # persists nothing), not silently substituting a real-looking 0.0 that
    # would then contaminate aggregation as if it were a genuine rating.


def _now() -> str:
    return datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%S")


# ── Input hashing / staleness (Part 9) ───────────────────────────────────────


def compute_topic_attribute_input_hash(
    *,
    topic_title: str,
    topic_angle: str,
    prompt_version: str,
) -> str:
    """Deterministic cache key for the DIRECT (orphan) characterization path.

    Includes prompt_version so bumping it naturally invalidates prior
    evaluations for future characterization without deleting historical
    rows — same convention as compute_semantic_fit_input_hash. Includes
    title/angle so an edited topic (update_topic changes title/angle)
    produces a different hash and is treated as needing a fresh
    evaluation rather than silently reusing a stale one.
    """
    payload = {
        "topic_title": topic_title,
        "topic_angle": topic_angle,
        "prompt_version": prompt_version,
    }
    return hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()[:32]


# ── Canonical persistence: topic_attribute_evaluations ───────────────────────


def get_cached_topic_attribute_evaluation(
    conn: sqlite3.Connection,
    *,
    topic_id: int,
    input_hash: str,
) -> sqlite3.Row | None:
    if not _table_exists(conn, "topic_attribute_evaluations"):
        return None
    return conn.execute(
        "SELECT * FROM topic_attribute_evaluations WHERE topic_id = ? AND input_hash = ?",
        (topic_id, input_hash),
    ).fetchone()


def save_topic_attribute_evaluation(
    conn: sqlite3.Connection,
    *,
    topic_id: int,
    source_opportunity_id: int | None,
    source_semantic_fit_result_id: int | None,
    prompt_name: str,
    prompt_version: str,
    provider_name: str,
    model: str,
    input_hash: str,
    values: TopicAttributeValues,
) -> None:
    """Persist one topic-attribute evaluation. Idempotent: a duplicate
    (topic_id, input_hash) is a no-op, never overwritten — old evaluations
    are never deleted or rewritten (Part 8/37)."""
    if not _table_exists(conn, "topic_attribute_evaluations"):
        return
    now = _now()
    # Persist the model's original human-readable domain_family text
    # verbatim, but only when it normalizes to something non-empty —
    # normalization (_normalize_domain_family) is used for counting only,
    # never for what gets stored.
    domain_family_to_store = (
        values.domain_family.strip()
        if _normalize_domain_family(values.domain_family) is not None
        else None
    )
    conn.execute(
        """
        INSERT INTO topic_attribute_evaluations (
            topic_id, source_opportunity_id, source_semantic_fit_result_id,
            prompt_name, prompt_version, provider_name, model, input_hash,
            practical_utility, immediate_payoff, curiosity, personal_relevance,
            surprise, broad_accessibility, niche_technicality, attribute_rationale,
            domain_family, evaluated_at, created_at
        ) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)
        ON CONFLICT (topic_id, input_hash) DO NOTHING
        """,
        (
            topic_id,
            source_opportunity_id,
            source_semantic_fit_result_id,
            prompt_name,
            prompt_version,
            provider_name,
            model,
            input_hash,
            values.practical_utility,
            values.immediate_payoff,
            values.curiosity,
            values.personal_relevance,
            values.surprise,
            values.broad_accessibility,
            values.niche_technicality,
            values.attribute_rationale or "",
            domain_family_to_store,
            now,
            now,
        ),
    )
    conn.commit()


def get_topic_attributes(conn: sqlite3.Connection, topic_id: int) -> TopicAttributeValues | None:
    """Canonical read API (Part 15). Returns the most recent evaluation for
    this topic, or None if the topic has never been characterized. Never
    infers attributes from a title, domain, or any other proxy."""
    if not _table_exists(conn, "topic_attribute_evaluations"):
        return None
    row = conn.execute(
        """
        SELECT * FROM topic_attribute_evaluations
         WHERE topic_id = ?
         ORDER BY evaluated_at DESC, id DESC
         LIMIT 1
        """,
        (topic_id,),
    ).fetchone()
    if row is None:
        return None
    return TopicAttributeValues.from_row(row)


def _table_exists(conn: sqlite3.Connection, name: str) -> bool:
    return (
        conn.execute(
            "SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (name,)
        ).fetchone()
        is not None
    )


# ── Normal forward path: snapshot from opportunity_semantic_fit_results ─────


def snapshot_semantic_fit_attributes_to_topic(
    conn: sqlite3.Connection,
    *,
    topic_id: int,
    opportunity_id: int,
) -> bool:
    """Copy the most recent cached semantic-fit attribute evaluation for
    `opportunity_id` onto `topic_id` (Part 7).

    Called from promote_opportunity() at the moment a topic is materialized.
    Zero provider calls: reads back what assess_semantic_fit already cached,
    potentially much earlier and in a different process.

    Returns False (never raises) when no cached semantic-fit row exists, or
    the cached row predates the attribute columns / attributes were never
    evaluated — a missing snapshot must never corrupt topic creation
    (Part 35/40).
    """
    if not _table_exists(conn, "opportunity_semantic_fit_results"):
        return False
    columns = {
        r["name"]
        for r in conn.execute("PRAGMA table_info('opportunity_semantic_fit_results')").fetchall()
    }
    if "practical_utility" not in columns:
        return False
    try:
        row = conn.execute(
            """
            SELECT * FROM opportunity_semantic_fit_results
             WHERE opportunity_id = ? AND practical_utility IS NOT NULL
             ORDER BY evaluated_at DESC, id DESC
             LIMIT 1
            """,
            (opportunity_id,),
        ).fetchone()
    except sqlite3.OperationalError:
        return False
    if row is None:
        return False

    values = TopicAttributeValues.from_row(row)
    # The snapshot's own idempotency key is the SOURCE semantic-fit row's
    # input_hash (not a re-derivation from topic title/angle, which the
    # orphan path uses) — this is the same evaluation, just materialized
    # onto a topic_id that didn't exist yet when it was computed. Re-running
    # promotion (already itself idempotent) must not create a duplicate.
    snapshot_hash = hashlib.sha256(
        json.dumps(
            {"source_semantic_fit_input_hash": row["input_hash"], "topic_id": topic_id},
            sort_keys=True,
        ).encode()
    ).hexdigest()[:32]

    save_topic_attribute_evaluation(
        conn,
        topic_id=topic_id,
        source_opportunity_id=opportunity_id,
        source_semantic_fit_result_id=row["id"],
        prompt_name="eligibility-semantic-fit",
        prompt_version=row["prompt_version"],
        provider_name=row["provider_name"],
        model=row["model"] or "",
        input_hash=snapshot_hash,
        values=values,
    )
    return True


# ── Orphan path: direct topic characterization ───────────────────────────────


def characterize_topic_directly(
    conn: sqlite3.Connection,
    *,
    topic_id: int,
    primary_niche: str,
    audience_description: str | None,
    ai_provider: object,
) -> TopicAttributeValues | None:
    """Direct one-call characterization for a topic with no opportunity to
    piggyback on (Part 10/11). Never fabricates an opportunity or
    semantic-fit row. Cached by (topic_id, input_hash) exactly like the
    forward path's snapshot.

    Returns None on any failure (missing topic, prompt error, provider
    error, malformed response) — never raises, never affects the topic or
    any publication/eligibility state (Part 12/35).
    """
    from app.ai.provider import AIRequest
    from app.ai.registry import PromptRegistry

    row = conn.execute("SELECT title, angle FROM topics WHERE id = ?", (topic_id,)).fetchone()
    if row is None:
        return None
    topic_title = row["title"] or ""
    topic_angle = row["angle"] or ""

    input_hash = compute_topic_attribute_input_hash(
        topic_title=topic_title,
        topic_angle=topic_angle,
        prompt_version=TOPIC_ATTRIBUTE_PROMPT_VERSION,
    )
    cached = get_cached_topic_attribute_evaluation(conn, topic_id=topic_id, input_hash=input_hash)
    if cached is not None:
        return TopicAttributeValues.from_row(cached)

    if ai_provider is None:
        return None

    try:
        registry = PromptRegistry()
        prompt = registry.get(TOPIC_ATTRIBUTE_PROMPT_NAME, TOPIC_ATTRIBUTE_PROMPT_VERSION)
        user_text = prompt.format_user(
            topic_title=topic_title or "(untitled)",
            topic_angle=topic_angle or "(no angle recorded)",
            primary_niche=primary_niche,
            audience_description=audience_description or "(not specified)",
        )
        model_id = getattr(ai_provider, "_model", None) or _TOPIC_ATTRIBUTE_MODEL
        request = AIRequest(
            system=prompt.system,
            user=user_text,
            model=model_id,
            response_schema=_TopicAttributeCharacterizationOutput,
        )
        response = ai_provider.complete(request)
        if response.parsed is None:
            return None
        output: _TopicAttributeCharacterizationOutput = response.parsed  # type: ignore[assignment]
    except Exception:
        return None

    values = TopicAttributeValues(
        evaluated=True,
        practical_utility=max(0.0, min(1.0, float(output.practical_utility))),
        immediate_payoff=max(0.0, min(1.0, float(output.immediate_payoff))),
        curiosity=max(0.0, min(1.0, float(output.curiosity))),
        personal_relevance=max(0.0, min(1.0, float(output.personal_relevance))),
        surprise=max(0.0, min(1.0, float(output.surprise))),
        broad_accessibility=max(0.0, min(1.0, float(output.broad_accessibility))),
        niche_technicality=max(0.0, min(1.0, float(output.niche_technicality))),
        attribute_rationale=output.attribute_rationale,
        domain_family=output.domain_family or None,
    )
    provider_name = getattr(ai_provider, "provider_name", None) or getattr(
        ai_provider, "name", "unknown"
    )
    save_topic_attribute_evaluation(
        conn,
        topic_id=topic_id,
        source_opportunity_id=None,
        source_semantic_fit_result_id=None,
        prompt_name=TOPIC_ATTRIBUTE_PROMPT_NAME,
        prompt_version=TOPIC_ATTRIBUTE_PROMPT_VERSION,
        provider_name=provider_name,
        model=model_id,
        input_hash=input_hash,
        values=values,
    )
    return values


def list_topics_needing_attribute_characterization(
    conn: sqlite3.Connection,
) -> list[dict]:
    """Bounded, read-only census for the human-triggered backfill CLI
    (Part 13/38, extended by the closure audit's Part 6): every UNIQUE
    published topic lacking a current canonical topic_attribute_evaluations
    row. Never executes a provider call itself.

    Each entry is classified into exactly one recovery class:
      - "orphan": promoted_opportunity_id IS NULL -> direct characterization
        (at most 1 provider call).
      - "snapshot": opportunity-linked AND a cached, attribute-bearing
        semantic-fit result already exists for that opportunity -> free
        snapshot, 0 provider calls.
      - "needs_characterization": opportunity-linked but no attribute-
        bearing cached semantic-fit result exists (e.g. it was evaluated
        under a pre-18H.C prompt version) -> direct characterization, at
        most 1 provider call. This closes the gap where such a topic would
        previously have been silently skipped by the backfill command
        entirely (Part 29 blocker D).
    """
    # Canonical criterion: an actual PUBLICATION row exists — not merely a
    # publishing_plans row. A rejected/never-published plan (confirmed live:
    # topic "history and society", plan status='rejected', zero publications)
    # must not enter the census; publishing_plans.status is never consulted
    # directly, since a genuinely published topic's plan can itself be in
    # various statuses ('draft', 'approved', ...) depending on when the
    # publication was created relative to the plan record.
    rows = conn.execute(
        """
        SELECT DISTINCT t.id AS topic_id, t.title, t.angle, t.promoted_opportunity_id
          FROM topics t
          JOIN publishing_plans pp ON pp.topic_id = t.id
          JOIN publications pub ON pub.publishing_plan_id = pp.id
         ORDER BY t.id
        """
    ).fetchall()
    has_attribute_columns = False
    if _table_exists(conn, "opportunity_semantic_fit_results"):
        cols = {
            r["name"]
            for r in conn.execute(
                "PRAGMA table_info('opportunity_semantic_fit_results')"
            ).fetchall()
        }
        has_attribute_columns = "practical_utility" in cols

    result: list[dict] = []
    for row in rows:
        if get_topic_attributes(conn, row["topic_id"]) is not None:
            continue
        opportunity_id = row["promoted_opportunity_id"]
        if opportunity_id is None:
            recovery_class = "orphan"
        elif (
            has_attribute_columns
            and conn.execute(
                "SELECT 1 FROM opportunity_semantic_fit_results"
                " WHERE opportunity_id = ? AND practical_utility IS NOT NULL LIMIT 1",
                (opportunity_id,),
            ).fetchone()
        ):
            recovery_class = "snapshot"
        else:
            recovery_class = "needs_characterization"
        result.append(
            {
                "topic_id": row["topic_id"],
                "title": row["title"],
                "promoted_opportunity_id": opportunity_id,
                "orphan": opportunity_id is None,
                "recovery_class": recovery_class,
            }
        )
    return result


# ── Cross-domain safeguard (Part 22) ─────────────────────────────────────────


def get_domain_family_for_publication(conn: sqlite3.Connection, publication_id: int) -> str | None:
    """Resolve a publication's topic-level SEMANTIC domain_family, if any.

    Closure-audit fix: resolves publication -> topic via the canonical
    publications.publishing_plan_id -> publishing_plans.topic_id lineage
    (the same lineage the aggregation query below now uses), then reads
    that topic's own topic_attribute_evaluations.domain_family. Returns
    None (never fabricated) when the publication/topic can't be resolved
    or the topic has not been characterized yet — an unknown domain can
    never by itself satisfy the >=2 distinct-domain-family requirement for
    'directional'/'actionable' maturity (see the cross-domain safeguard in
    _upsert_topic_attribute_observation), it just contributes nothing to
    the count.
    """
    row = conn.execute(
        """
        SELECT pp.topic_id
          FROM publications pub
          JOIN publishing_plans pp ON pub.publishing_plan_id = pp.id
         WHERE pub.id = ?
        """,
        (publication_id,),
    ).fetchone()
    if row is None:
        return None
    attrs = get_topic_attributes(conn, row["topic_id"])
    if attrs is None:
        return None
    return _normalize_domain_family(attrs.domain_family)


