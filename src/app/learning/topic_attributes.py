class TopicAttributePerformanceObservation(BaseModel):
    """Frozen projection of a topic_attribute_performance_observations row.

    Semantics: "In this channel, publications whose topic's {attribute_name}
    fell into bucket '{attribute_bucket}' had {observation_type} with outcome
    metric {metric_name}: mean={mean} (n={publication_count} publications
    across {distinct_topic_count} topics, {distinct_domain_family_count}
    domain families)." observation_type is always 'association'.
    """

    model_config = {"frozen": True}

    id: int
    channel_id: str
    workspace_id: str | None
    attribute_name: str
    attribute_bucket: str
    metric_name: str
    period_type: str
    publication_count: int
    distinct_topic_count: int
    distinct_domain_family_count: int
    mean: float | None
    median: float | None
    min_value: float | None
    max_value: float | None
    std_dev: float | None
    baseline_mean: float | None
    baseline_median: float | None
    abs_diff_from_baseline: float | None
    rel_diff_from_baseline: float | None
    sample_maturity: str
    observation_type: str
    source_publication_ids_json: str
    source_topic_ids_json: str
    comparison_schema_version: str
    observer_version: str
    input_hash: str
    created_at: str
    updated_at: str

    @classmethod
    def from_row(cls, row: sqlite3.Row) -> TopicAttributePerformanceObservation:
        return cls(**dict(row))

    @property
    def source_publication_ids(self) -> list[int]:
        try:
            return json.loads(self.source_publication_ids_json)
        except (json.JSONDecodeError, TypeError):
            return []

    @property
    def source_topic_ids(self) -> list[int]:
        try:
            return json.loads(self.source_topic_ids_json)
        except (json.JSONDecodeError, TypeError):
            return []


